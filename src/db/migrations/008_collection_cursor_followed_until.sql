-- 収集カーソルに「どこまで最新を追ったか」を足す（#11 / CONTEXT.md の収集カーソル）。
--
-- CONTEXT.md は収集カーソルを「どこまで過去へ遡ったか」と「どこまで最新を追ったか」の
-- 両方を持つ状態として定義しているが、005 では前者（backfilled_until）しか無かった。
-- 最新を追う収集の起点がどこにも残らず、起動のたびに「いつから取り直すか」を決められない。
--
-- last_success_at で代用しない。あれは「収集サイクルがいつ成功したか」であって、
-- 「どの時刻までのイベントを取り込んだか」ではない。1 窓だけ取ってレート制限で中断した
-- サイクルは失敗として記録されるが、取り込んだ範囲は確定している。両者を混ぜると、
-- 中断のたびに取り直すか、逆に取り込んでいない範囲を取り込み済みとみなして取りこぼす。
ALTER TABLE collection_cursors ADD COLUMN followed_until TEXT;
